/* Lexicon Explorer — tree-mode view logic.
   Loads vocabularies.json (generated by build-vocabularies-json.ts) and renders 4 views.
*/

let DATA = null;

async function init() {
  try {
    const r = await fetch("vocabularies.json");
    DATA = await r.json();
  } catch (e) {
    document.getElementById("main").innerHTML =
      `<div style="padding:20px"><strong>Could not load vocabularies.json.</strong> ` +
      `Run <code>bun build-vocabularies-json.ts</code> in this directory first.</div>`;
    return;
  }
  document.getElementById("meta-line").textContent =
    `${DATA.lexicons.length} lexicons · ${DATA.lexicons.reduce((s,l)=>s+l.cards.length,0)} cards · built ${DATA.generatedAt}`;

  document.querySelectorAll("#view-tabs button").forEach((btn) => {
    btn.addEventListener("click", () => switchView(btn.dataset.view));
  });
  switchView("picker");
}

function switchView(view) {
  document.querySelectorAll("#view-tabs button").forEach((b) => {
    b.classList.toggle("active", b.dataset.view === view);
  });
  const main = document.getElementById("main");
  main.innerHTML = "";
  if (view === "picker")    renderPicker(main);
  if (view === "compare")   renderCompare(main);
  if (view === "category")  renderCategoryView(main);
  if (view === "closest")   renderClosestFit(main);
}

// ─── Helpers ──────────────────────────────────────────────────────

function escapeHtml(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;", "'": "&#39;",
  }[c]));
}

function truncate(s, n) {
  s = String(s ?? "").trim();
  if (s.length <= n) return s;
  return s.slice(0, n).trim().replace(/\s+\S*$/, "") + "…";
}

function cleanWhat(s) {
  return String(s ?? "")
    .replace(/^_Stub —\s*/i, "")
    .replace(/_Stub —\s*/gi, "")
    .replace(/^_(.+)_$/gm, "$1")
    .trim();
}

function userVisibleAttr(card) {
  if (card.user_visible === true)  return "true";
  if (card.user_visible === false) return "false";
  return "null";
}

function categoryLabelFor(folderName) {
  return DATA.folderToCategory && DATA.folderToCategory[folderName]
    ? DATA.folderToCategory[folderName]
    : folderName;
}

function countCardsIn(node) {
  if (node.type === "card") return 1;
  return node.children.reduce((s, c) => s + countCardsIn(c), 0);
}

// ─── Tree renderer (shared) ──────────────────────────────────────

/**
 * Renders a tree node into `parentEl` at the given depth.
 * Folders start collapsed unless depth < openDepth.
 */
function renderTreeNode(node, parentEl, depth, openDepth) {
  if (node.type === "card") {
    const el = document.createElement("div");
    el.className = "tree-card";
    el.dataset.visible = userVisibleAttr(node.card);
    el.style.paddingLeft = (depth * 18 + 12) + "px";
    const facetMark = node.card.facets && node.card.facets.length > 0
      ? ` <span class="facet-mark" title="facets: ${escapeHtml(node.card.facets.join(", "))}">⬗</span>`
      : "";
    el.innerHTML =
      `<span class="tree-icon">📄</span>` +
      `<span class="tree-card-label">${escapeHtml(node.card.prefLabel)}</span>` +
      `<span class="tree-card-type">${escapeHtml(node.card.type)}</span>${facetMark}`;
    el.addEventListener("click", (e) => {
      e.stopPropagation();
      const next = el.nextElementSibling;
      if (next && next.classList.contains("tree-card-detail")) {
        next.remove();
      } else {
        const detail = renderCardDetail(node.card, depth + 1);
        el.parentNode.insertBefore(detail, el.nextSibling);
      }
    });
    parentEl.appendChild(el);
    return;
  }

  // folder
  const cardCount = countCardsIn(node);
  const folderEl = document.createElement("div");
  folderEl.className = "tree-folder";
  folderEl.style.paddingLeft = (depth * 18) + "px";

  const isCategoryFolder = depth === 0 && DATA.folderToCategory && DATA.folderToCategory[node.name];
  const label = isCategoryFolder ? categoryLabelFor(node.name) : node.name;

  folderEl.innerHTML =
    `<span class="tree-caret">▶</span>` +
    `<span class="tree-icon">📁</span>` +
    `<span class="tree-folder-label">${escapeHtml(label)}</span>` +
    `<span class="tree-folder-count">${cardCount}</span>`;
  parentEl.appendChild(folderEl);

  const childrenContainer = document.createElement("div");
  childrenContainer.className = "tree-children";
  parentEl.appendChild(childrenContainer);

  for (const child of node.children) {
    renderTreeNode(child, childrenContainer, depth + 1, openDepth);
  }

  // Only auto-expand if depth is strictly less than openDepth
  const startExpanded = depth < openDepth;
  childrenContainer.style.display = startExpanded ? "block" : "none";
  folderEl.querySelector(".tree-caret").textContent = startExpanded ? "▼" : "▶";
  if (startExpanded) folderEl.classList.add("open");

  folderEl.addEventListener("click", (e) => {
    e.stopPropagation();
    const open = childrenContainer.style.display !== "none";
    childrenContainer.style.display = open ? "none" : "block";
    folderEl.querySelector(".tree-caret").textContent = open ? "▶" : "▼";
    folderEl.classList.toggle("open", !open);
  });
}

function renderCardDetail(card, depth) {
  const el = document.createElement("div");
  el.className = "tree-card-detail";
  el.style.paddingLeft = (depth * 18 + 18) + "px";
  const what = cleanWhat(card.what);
  const altLabels = card.altLabels.length > 0
    ? `<div class="cd-row"><strong>aka:</strong> ${escapeHtml(card.altLabels.join(", "))}</div>` : "";
  const subcat = card.subcategory.length > 0
    ? `<div class="cd-row"><strong>subcategory:</strong> ${escapeHtml(card.subcategory.join(" / "))}</div>` : "";
  const facets = card.facets.length > 0
    ? `<div class="cd-row"><strong>facets:</strong> ${escapeHtml(card.facets.join(", "))}</div>` : "";
  const sources = card.source_evidence.length > 0
    ? `<div class="cd-row source"><strong>source:</strong> ${card.source_evidence.map((s) =>
        s.startsWith("http")
          ? `<a href="${escapeHtml(s)}" target="_blank">${escapeHtml(s)}</a>`
          : escapeHtml(s)).join(", ")}</div>` : "";
  el.innerHTML =
    `<div class="cd-path">${escapeHtml(card.filePath)}</div>` +
    altLabels + subcat + facets +
    `<div class="cd-what">${escapeHtml(truncate(what, 400))}</div>` +
    sources;
  return el;
}

// ─── Picker view ─────────────────────────────────────────────────

function renderPicker(root) {
  const layout = document.createElement("div");
  layout.className = "picker-layout";

  const sidebar = document.createElement("aside");
  sidebar.className = "lexicon-list";

  const content = document.createElement("div");
  content.className = "lexicon-content";

  DATA.lexicons.forEach((lex, i) => {
    const btn = document.createElement("button");
    btn.className = "lexicon-btn";
    btn.dataset.id = lex.id;
    btn.innerHTML =
      `<span class="lex-name">${escapeHtml(lex.name)}</span>` +
      `<span class="lex-stats">${lex.stats.totalCards}</span>`;
    btn.addEventListener("click", () => {
      sidebar.querySelectorAll(".lexicon-btn").forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      renderLexiconDetail(content, lex);
    });
    sidebar.appendChild(btn);
    if (i === 0) btn.classList.add("active");
  });

  layout.appendChild(sidebar);
  layout.appendChild(content);
  root.appendChild(layout);

  renderLexiconDetail(content, DATA.lexicons[0]);
}

function renderLexiconDetail(root, lex) {
  root.innerHTML = "";

  const header = document.createElement("section");
  header.className = "lex-header";
  const previewLine = (lex.readmePreview || "").split("\n\n")[0] || "";
  header.innerHTML = `
    <h2>${escapeHtml(lex.name)} Vocabulary</h2>
    <p class="lex-preview">${escapeHtml(truncate(previewLine, 280))}</p>
    <div class="lex-stats-row">
      <span>${lex.stats.totalCards} cards</span>
      <span>${lex.stats.facetCards} facet</span>
      <span>${lex.stats.userVisibleTrueCount} user-visible</span>
      <span>${lex.stats.userVisibleFalseCount} engine-internal</span>
      <span>depth ${lex.stats.maxDepth}</span>
    </div>
  `;
  root.appendChild(header);

  if (lex.signature && lex.signature.rules && lex.signature.rules.length > 0) {
    const sig = document.createElement("section");
    sig.className = "signature-card";
    sig.innerHTML =
      `<h3>Nomenclature Signature</h3>` +
      `<ol>${lex.signature.rules.map((r) => {
        const idx = r.indexOf(" — ");
        if (idx > 0) return `<li><strong>${escapeHtml(r.slice(0, idx))}</strong> ${escapeHtml(r.slice(idx + 3))}</li>`;
        return `<li>${escapeHtml(r)}</li>`;
      }).join("")}</ol>`;
    root.appendChild(sig);
  }

  // Tree section — only top-level category folders rendered; everything below collapsed.
  const treeSection = document.createElement("section");
  treeSection.className = "tree-section";
  treeSection.innerHTML = `<h3 class="tree-section-heading">Library tree <span class="hint">— click folders to drill in, click a card for detail</span></h3>`;
  const treeRoot = document.createElement("div");
  treeRoot.className = "tree-root";
  // openDepth = 0 means even top-level folders start collapsed.
  // We want to SEE the top-level category folders, so we render them and let user expand.
  for (const folder of lex.tree) {
    renderTreeNode(folder, treeRoot, 0, /*openDepth*/ 0);
  }
  treeSection.appendChild(treeRoot);
  root.appendChild(treeSection);

  if (lex.deprecations.length > 0) {
    const section = document.createElement("section");
    section.className = "deprecations";
    section.innerHTML = `<h3>Deprecation tombstones <span class="count">${lex.deprecations.length}</span></h3>`;
    const list = document.createElement("div");
    list.className = "tree-root";
    for (const dep of lex.deprecations) {
      renderTreeNode({ type: "card", card: dep }, list, 0, 0);
    }
    section.appendChild(list);
    root.appendChild(section);
  }
}

// ─── Compare view ─────────────────────────────────────────────────

function renderCompare(root) {
  const controls = document.createElement("div");
  controls.className = "compare-controls";
  controls.innerHTML = `
    <label>Left: <select id="cmp-left"></select></label>
    <label>Right: <select id="cmp-right"></select></label>
  `;
  root.appendChild(controls);

  const pane = document.createElement("div");
  pane.className = "compare-pane";
  root.appendChild(pane);

  const left = controls.querySelector("#cmp-left");
  const right = controls.querySelector("#cmp-right");
  DATA.lexicons.forEach((lex, i) => {
    left.add(new Option(lex.name, i));
    right.add(new Option(lex.name, i));
  });
  const linearIdx = DATA.lexicons.findIndex((l) => l.id === "linear");
  const alxIdx = DATA.lexicons.findIndex((l) => l.id === "alexandria");
  left.value = alxIdx >= 0 ? alxIdx : 0;
  right.value = linearIdx >= 0 ? linearIdx : Math.min(1, DATA.lexicons.length - 1);

  const render = () => {
    const a = DATA.lexicons[parseInt(left.value, 10)];
    const b = DATA.lexicons[parseInt(right.value, 10)];
    pane.innerHTML = "";

    const table = document.createElement("table");
    table.className = "compare-table";
    table.innerHTML = `
      <thead><tr>
        <th>Category</th>
        <th>${escapeHtml(a.name)} <span class="th-count">(${a.stats.totalCards})</span></th>
        <th>${escapeHtml(b.name)} <span class="th-count">(${b.stats.totalCards})</span></th>
      </tr></thead>
    `;
    const tbody = document.createElement("tbody");

    const allFolders = new Set();
    a.tree.forEach((t) => allFolders.add(t.name));
    b.tree.forEach((t) => allFolders.add(t.name));
    const orderedFolders = [...allFolders].sort((x, y) => {
      const ox = DATA.universalCategories.indexOf(categoryLabelFor(x));
      const oy = DATA.universalCategories.indexOf(categoryLabelFor(y));
      return (ox === -1 ? 999 : ox) - (oy === -1 ? 999 : oy);
    });

    const treeForFolder = (lex, folderName) => lex.tree.find((f) => f.name === folderName);

    for (const folder of orderedFolders) {
      const aTree = treeForFolder(a, folder);
      const bTree = treeForFolder(b, folder);
      const tr = document.createElement("tr");
      const aCell = document.createElement("td");
      const bCell = document.createElement("td");
      aCell.className = "compare-cell";
      bCell.className = "compare-cell";
      const renderInto = (cell, tree) => {
        if (!tree || tree.children.length === 0) {
          cell.innerHTML = `<em class="empty">—</em>`;
          return;
        }
        const wrap = document.createElement("div");
        wrap.className = "compare-tree";
        // Render the IMMEDIATE children of the category — collapsed by default.
        for (const child of tree.children) {
          renderTreeNode(child, wrap, 0, /*openDepth*/ 0);
        }
        cell.appendChild(wrap);
      };
      renderInto(aCell, aTree);
      renderInto(bCell, bTree);
      tr.innerHTML = `<td class="cat-label">${escapeHtml(categoryLabelFor(folder))}</td>`;
      tr.appendChild(aCell);
      tr.appendChild(bCell);
      tbody.appendChild(tr);
    }

    table.appendChild(tbody);
    pane.appendChild(table);
  };

  left.addEventListener("change", render);
  right.addEventListener("change", render);
  render();
}

// ─── Category view (one category × all lexicons) ────────────────

function renderCategoryView(root) {
  const controls = document.createElement("div");
  controls.className = "category-controls";
  const label = document.createElement("span");
  label.style.fontFamily = "var(--font-mono)";
  label.style.fontSize = "12px";
  label.style.color = "var(--ink-dim)";
  label.textContent = "Category:";
  const pick = document.createElement("div");
  pick.className = "cat-pick";
  const folderNames = Object.keys(DATA.folderToCategory);
  folderNames.forEach((folderName) => {
    const btn = document.createElement("button");
    btn.textContent = categoryLabelFor(folderName);
    btn.dataset.folder = folderName;
    btn.addEventListener("click", () => {
      pick.querySelectorAll("button").forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      render(folderName);
    });
    pick.appendChild(btn);
  });
  controls.appendChild(label);
  controls.appendChild(pick);
  root.appendChild(controls);

  const pane = document.createElement("div");
  pane.className = "category-pane";
  root.appendChild(pane);

  const render = (folderName) => {
    pane.innerHTML = "";
    const grid = document.createElement("div");
    grid.className = "category-grid";
    DATA.lexicons.forEach((lex) => {
      const folder = lex.tree.find((t) => t.name === folderName);
      const col = document.createElement("div");
      col.className = "cat-col";
      const cardCount = folder ? countCardsIn(folder) : 0;
      const heading = `<h4>${escapeHtml(lex.name)} <span class="th-count">(${cardCount})</span></h4>`;
      if (!folder || cardCount === 0) {
        col.innerHTML = heading + `<div class="empty-note">no cards in this category</div>`;
      } else {
        col.innerHTML = heading;
        const wrap = document.createElement("div");
        wrap.className = "category-tree";
        // Show immediate children, collapsed
        for (const child of folder.children) {
          renderTreeNode(child, wrap, 0, /*openDepth*/ 0);
        }
        col.appendChild(wrap);
      }
      grid.appendChild(col);
    });
    pane.appendChild(grid);
  };

  const defaultFolder = "roles";
  const defaultBtn = pick.querySelector(`button[data-folder="${defaultFolder}"]`);
  if (defaultBtn) defaultBtn.classList.add("active");
  render(defaultFolder);
}

// ─── Closest-fit picker ──────────────────────────────────────────

function renderClosestFit(root) {
  const pane = document.createElement("div");
  pane.className = "closest-pane";
  pane.innerHTML = `
    <h2>Closest-fit picker</h2>
    <p>Describe your product in one or two sentences. The picker ranks the 8 Vocabularies by keyword overlap with their signatures, stub names, and definitions.</p>
    <textarea id="cf-input" placeholder="e.g. We build a B2B SaaS workspace for product teams to track issues across teams and cycles."></textarea>
    <button class="rank-btn" id="cf-btn">Rank vocabularies</button>
    <div class="closest-results" id="cf-results"></div>
  `;
  root.appendChild(pane);

  pane.querySelector("#cf-btn").addEventListener("click", () => {
    const text = pane.querySelector("#cf-input").value.trim();
    renderClosestResults(pane.querySelector("#cf-results"), text);
  });
  pane.querySelector("#cf-input").addEventListener("keydown", (e) => {
    if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) {
      pane.querySelector("#cf-btn").click();
    }
  });
}

const STOPWORDS = new Set([
  "the","a","an","of","and","or","is","to","for","in","on","at","by","with","we","our","your","my",
  "i","you","they","them","be","that","this","it","as","build","building","make","making","create"
]);

function tokens(s) {
  return String(s ?? "")
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 2 && !STOPWORDS.has(w));
}

function renderClosestResults(root, query) {
  root.innerHTML = "";
  if (!query) {
    root.innerHTML = `<em class="empty">Type a description above, then click Rank.</em>`;
    return;
  }
  const queryToks = new Set(tokens(query));

  const scored = DATA.lexicons.map((lex) => {
    const pool = [
      lex.name,
      lex.readmePreview || "",
      ...(lex.signature ? lex.signature.rules : []),
      lex.signature ? lex.signature.what : "",
      ...lex.cards.map((c) => c.prefLabel),
      ...lex.cards.flatMap((c) => c.altLabels),
    ].join(" ");
    const lexToks = tokens(pool);
    const lexSet = new Set(lexToks);
    let score = 0;
    const matched = [];
    queryToks.forEach((qt) => {
      if (lexSet.has(qt)) {
        score++;
        matched.push(qt);
      }
    });
    if (queryToks.size > 0) {
      tokens(lex.name).forEach((nt) => {
        if (queryToks.has(nt)) score += 2;
      });
    }
    return { lex, score, matched };
  }).sort((a, b) => b.score - a.score);

  scored.forEach((r, i) => {
    const el = document.createElement("div");
    el.className = "closest-result" + (i === 0 ? " top" : "");
    const matchedHtml = r.matched.length > 0
      ? `<div class="why"><strong>Matched terms:</strong> ${r.matched.map(escapeHtml).join(", ")}</div>`
      : `<div class="why">no shared terms</div>`;
    el.innerHTML = `
      <h3>${i === 0 ? "✦ " : ""}${escapeHtml(r.lex.name)} <span class="score">score ${r.score}</span></h3>
      <div class="why">${escapeHtml(truncate(r.lex.readmePreview.split("\n\n")[0] || "", 220))}</div>
      ${matchedHtml}
    `;
    root.appendChild(el);
  });
}

